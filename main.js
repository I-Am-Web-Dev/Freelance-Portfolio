    const languageButton = document.getElementById("languageButton");
    const languageMenu = document.getElementById("languageMenu");
    const currentLanguage = document.getElementById("currentLanguage");


    function getTranslation(object, path) {
        return path
            .split(".")
            .reduce((result, key) => result?.[key], object);
    }


    function setLanguage(language) {

        const translation = translations[language];

        if (!translation) return;

        document.documentElement.lang = language;
        document.documentElement.dir = language === "ar" ? "rtl" : "ltr";

        document.querySelectorAll("[data-i18n]").forEach(element => {

            const key = element.getAttribute("data-i18n");
            const value = getTranslation(translation, key);

            if (value !== undefined) {
                element.innerHTML = value;
            }

        });


        document.querySelectorAll("[data-i18n-alt]").forEach(element => {

            const key = element.getAttribute("data-i18n-alt");
            const value = getTranslation(translation, key);

            if (value !== undefined) {
                element.alt = value;
            }

        });


        currentLanguage.textContent = language.toUpperCase();

        localStorage.setItem("preferredLanguage", language);

        languageMenu.classList.remove("active");
        languageButton.setAttribute("aria-expanded", "false");
    }


    languageButton.addEventListener("click", () => {

        const isOpen = languageMenu.classList.toggle("active");

        languageButton.setAttribute(
            "aria-expanded",
            isOpen ? "true" : "false"
        );

    });


    document.querySelectorAll("[data-language]").forEach(button => {

        button.addEventListener("click", () => {

            const language = button.getAttribute("data-language");

            setLanguage(language);

        });

    });


    document.addEventListener("click", event => {

        if (
            !languageButton.contains(event.target) &&
            !languageMenu.contains(event.target)
        ) {
            languageMenu.classList.remove("active");

            languageButton.setAttribute("aria-expanded", "false");
        }

    });


    const savedLanguage = localStorage.getItem("preferredLanguage");

    if (savedLanguage && translations[savedLanguage]) {
        setLanguage(savedLanguage);
    } else {
        setLanguage("en");
    }
